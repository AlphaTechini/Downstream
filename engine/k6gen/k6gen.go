// Package k6gen turns a validated journeys file into a k6 script and reads back
// the per-step figures the script writes. The script is a fixed interpreter;
// everything the model supplied is embedded as one JSON literal and is never
// placed into JavaScript source in any other way.
package k6gen

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"errors"
	"fmt"
	"net/url"
	"regexp"
	"strconv"
	"strings"
	"time"

	"downstream/engine/model"
)

// Options configure one generated script.
type Options struct {
	BaseURL     string // must be http://127.0.0.1:<port>
	VUs         int
	Iterations  int // per VU
	MaxDuration time.Duration
	RunID       string // [a-z0-9_]{0,32}; makes {{uniq}} differ between runs
}

//go:embed interpreter.js
var interpreter string

var (
	idRe    = regexp.MustCompile(`^[a-z0-9_]{1,40}$`)
	runIDRe = regexp.MustCompile(`^[a-z0-9_]{0,32}$`)
)

// CheckBaseURL is the loopback guarantee: only http://127.0.0.1:<port> passes.
func CheckBaseURL(raw string) error {
	u, err := url.Parse(raw)
	if err != nil {
		return fmt.Errorf("base URL %q: %w", raw, err)
	}
	if u.Scheme != "http" || u.Hostname() != "127.0.0.1" || u.User != nil ||
		(u.Path != "" && u.Path != "/") || u.RawQuery != "" || u.Fragment != "" || u.Opaque != "" {
		return fmt.Errorf("base URL %q must be http://127.0.0.1:<port>", raw)
	}
	port, err := strconv.Atoi(u.Port())
	if err != nil || port < 1 || port > 65535 || strconv.Itoa(port) != u.Port() {
		return fmt.Errorf("base URL %q needs a numeric port", raw)
	}
	return nil
}

// Script renders the k6 script for f.
func Script(f model.JourneyFile, o Options) (string, error) {
	if err := CheckBaseURL(o.BaseURL); err != nil {
		return "", err
	}
	var errs []error
	if o.VUs < 1 || o.VUs > 100 {
		errs = append(errs, fmt.Errorf("VUs must be 1 to 100, got %d", o.VUs))
	}
	if o.Iterations < 1 {
		errs = append(errs, fmt.Errorf("iterations must be at least 1, got %d", o.Iterations))
	}
	if o.MaxDuration < time.Second {
		errs = append(errs, fmt.Errorf("max duration must be at least 1s, got %s", o.MaxDuration))
	}
	if !runIDRe.MatchString(o.RunID) {
		errs = append(errs, fmt.Errorf("run id %q must match [a-z0-9_]{0,32}", o.RunID))
	}
	if len(f.Journeys) == 0 {
		errs = append(errs, errors.New("no journeys"))
	}
	// The same checks journey.Validate makes on names, repeated here because
	// names end up in metric names and function names.
	seen := map[string]bool{}
	for _, j := range f.Journeys {
		if !idRe.MatchString(j.ID) {
			errs = append(errs, fmt.Errorf("journey id %q must match [a-z0-9_]{1,40}", j.ID))
			continue
		}
		if len(j.Steps) == 0 {
			errs = append(errs, fmt.Errorf("journey %q has no steps", j.ID))
		}
		for _, s := range j.Steps {
			if !idRe.MatchString(s.Name) {
				errs = append(errs, fmt.Errorf("journey %q step name %q must match [a-z0-9_]{1,40}", j.ID, s.Name))
				continue
			}
			key := j.ID + "__" + s.Name
			if seen[key] {
				errs = append(errs, fmt.Errorf("journey %q step %q: metric name %q is not unique", j.ID, s.Name, key))
			}
			seen[key] = true
		}
		if seen["journey:"+j.ID] {
			errs = append(errs, fmt.Errorf("journey id %q is used twice", j.ID))
		}
		seen["journey:"+j.ID] = true
	}
	if err := errors.Join(errs...); err != nil {
		return "", err
	}

	lit, err := jsLiteral(f.Journeys)
	if err != nil {
		return "", err
	}
	base, err := jsLiteral(strings.TrimSuffix(o.BaseURL, "/"))
	if err != nil {
		return "", err
	}
	runID := o.RunID
	if runID == "" {
		runID = "r"
	}
	runLit, _ := jsLiteral(runID)
	maxSecs := int((o.MaxDuration + time.Second - 1) / time.Second)

	var b strings.Builder
	b.WriteString("// Generated by downstream. Journeys are data; the interpreter below is fixed.\n")
	b.WriteString("import http from 'k6/http';\nimport { Trend, Counter } from 'k6/metrics';\nimport { sleep } from 'k6';\n\n")
	fmt.Fprintf(&b, "const BASE = %s;\nconst RUN_ID = %s;\nconst VUS = %d;\nconst ITERATIONS = %d;\nconst MAX_DURATION = '%ds';\n", base, runLit, o.VUs, o.Iterations, maxSecs)
	fmt.Fprintf(&b, "const JOURNEYS = %s;\n\n", lit)
	b.WriteString(interpreter)
	b.WriteString("\n")
	for i, j := range f.Journeys {
		fmt.Fprintf(&b, "export function %s() { runJourney(JOURNEYS[%d]); }\n", ExecName(j.ID), i)
	}
	return b.String(), nil
}

// ExecName is the exported function that runs journey id. The prefix keeps
// ids that start with a digit, or equal a reserved word, valid as identifiers.
func ExecName(id string) string { return "j_" + id }

// jsLiteral encodes v as JSON, which is a JavaScript expression, with the two
// line separators that older engines reject inside string literals escaped.
func jsLiteral(v any) (string, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(true)
	if err := enc.Encode(v); err != nil {
		return "", err
	}
	s := strings.TrimSpace(buf.String())
	s = strings.ReplaceAll(s, " ", ` `)
	s = strings.ReplaceAll(s, " ", ` `)
	return s, nil
}

// ParseSummary reads steps.json as written by the script's handleSummary.
func ParseSummary(data []byte) ([]model.StepMetrics, error) {
	var out []model.StepMetrics
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&out); err != nil {
		return nil, fmt.Errorf("steps.json: %w", err)
	}
	if len(out) == 0 {
		return nil, errors.New("steps.json: no steps")
	}
	for _, m := range out {
		if m.Journey == "" || m.Step == "" {
			return nil, errors.New("steps.json: an entry has no journey or step name")
		}
		if m.Count < 0 || m.Failures < 0 || m.P50 < 0 || m.P95 < 0 || m.Mean < 0 {
			return nil, fmt.Errorf("steps.json: %s/%s has a negative figure", m.Journey, m.Step)
		}
	}
	return out, nil
}
